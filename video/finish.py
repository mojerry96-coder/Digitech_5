"""Export the deliverables into ../public/walkthrough/ from the paced cut.

Run from this folder after pace.py. Writes:
  qcs-walkthrough-1080p.mp4                (H.264/AAC; no embedded captions, so none show by default)
  qcs-walkthrough-1080p.webm               (VP9/Opus, for browsers without H.264)
  qcs-walkthrough-1080p-open-captions.mp4  (captions burned in)
  captions.srt, captions.vtt, captions.js (for the player), transcript.md
"""
import json, os, shutil, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "public", "walkthrough")
os.chdir(HERE)
os.makedirs(OUT, exist_ok=True)
cues = json.load(open("paced-cues.json"))
base = os.path.join(OUT, "qcs-walkthrough-1080p")
voice = open("narration/VOICE").read().strip() if os.path.exists("narration/VOICE") else "unknown"


def ts(x, sep=","):
    h, m, s = int(x // 3600), int(x % 3600 // 60), x % 60
    return f"{h:02d}:{m:02d}:{int(s):02d}{sep}{int(round((s - int(s)) * 1000)):03d}"


srt = "\n".join(f"{i + 1}\n{ts(c['s'])} --> {ts(c['e'])}\n{c['t']}\n" for i, c in enumerate(cues))
vtt = "WEBVTT\n\n" + "\n".join(f"{ts(c['s'], '.')} --> {ts(c['e'], '.')}\n{c['t']}\n" for c in cues)
open(os.path.join(OUT, "captions.srt"), "w").write(srt)
open(os.path.join(OUT, "captions.vtt"), "w").write(vtt)
# The player reads its captions from this script, so they also work from a static copy
open(os.path.join(OUT, "captions.js"), "w").write("/* Generated by video/finish.py */\nwindow.WALKTHROUGH_CUES = " + json.dumps(cues, ensure_ascii=False) + ";\n")

dur = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", "paced-clean.mp4"]).decode())
lines = ["# Walkthrough transcript: The Qualitative Coding Sandbox", "",
         f"{round(dur)} seconds · narration: {voice} · captions off by default", ""]
lines += [f"- **{int(c['s'] // 60)}:{c['s'] % 60:05.2f}** {c['t']}" for c in cues]
open(os.path.join(OUT, "transcript.md"), "w").write("\n".join(lines) + "\n")

run = lambda *a: subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *a], check=True)
shutil.copy("paced-clean.mp4", base + ".mp4")  # no embedded caption track: MP4 players would switch it on
shutil.copy("paced-burned.mp4", base + "-open-captions.mp4")
run("-i", "paced-clean.mp4", "-c:v", "libvpx-vp9", "-b:v", "0", "-crf", "34", "-row-mt", "1", "-deadline", "good", "-cpu-used", "4",
    "-c:a", "libopus", "-b:a", "96k", base + ".webm")
for f in sorted(os.listdir(OUT)):
    print(f"{f:44s} {os.path.getsize(os.path.join(OUT, f)) / 1e6:6.2f} MB")
